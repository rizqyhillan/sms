CREATE TABLE IF NOT EXISTS konsultasi_bk (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 siswa_id BIGINT UNSIGNED NOT NULL,
 tahun_pelajaran_id BIGINT UNSIGNED NOT NULL,
 tanggal DATE NOT NULL,
 waktu TIME NULL,
 jenis ENUM('siswa','orang_tua','wali_kelas','guru','lainnya') NOT NULL DEFAULT 'siswa',
 topik VARCHAR(190) NOT NULL,
 permasalahan TEXT NULL,
 hasil TEXT NULL,
 kesepakatan TEXT NULL,
 tindak_lanjut TEXT NULL,
 status ENUM('baru','proses','selesai','dibatalkan') NOT NULL DEFAULT 'baru',
 melibatkan_ortu TINYINT(1) NOT NULL DEFAULT 0,
 petugas_id BIGINT UNSIGNED NULL,
 created_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id),
 KEY idx_kons50_siswa(siswa_id), KEY idx_kons50_tapel(tahun_pelajaran_id), KEY idx_kons50_tanggal(tanggal), KEY idx_kons50_status(status),
 CONSTRAINT fk_kons50_siswa FOREIGN KEY(siswa_id) REFERENCES siswa(id) ON UPDATE CASCADE,
 CONSTRAINT fk_kons50_tapel FOREIGN KEY(tahun_pelajaran_id) REFERENCES tahun_pelajaran(id) ON UPDATE CASCADE,
 CONSTRAINT fk_kons50_petugas FOREIGN KEY(petugas_id) REFERENCES guru(id) ON DELETE SET NULL ON UPDATE CASCADE,
 CONSTRAINT fk_kons50_created FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
