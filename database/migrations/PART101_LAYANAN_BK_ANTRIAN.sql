CREATE TABLE IF NOT EXISTS bk_layanan (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  siswa_id BIGINT UNSIGNED NOT NULL,
  tahun_pelajaran_id BIGINT UNSIGNED NOT NULL,
  kelas_id BIGINT UNSIGNED NULL,
  tanggal DATE NOT NULL,
  nomor_antrian INT UNSIGNED NOT NULL,
  waktu_masuk DATETIME NOT NULL,
  status ENUM('menunggu','dilayani','selesai','batal') NOT NULL DEFAULT 'menunggu',
  jenis_layanan ENUM('konseling','konsultasi','rujukan','administratif','lainnya') NULL,
  waktu_mulai DATETIME NULL,
  waktu_selesai DATETIME NULL,
  topik VARCHAR(190) NULL,
  permasalahan TEXT NULL,
  hasil TEXT NULL,
  kesepakatan TEXT NULL,
  tindak_lanjut TEXT NULL,
  melibatkan_ortu TINYINT(1) NOT NULL DEFAULT 0,
  metode_masuk ENUM('QR','USB','MANUAL') NOT NULL DEFAULT 'QR',
  petugas_id BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_bk_layanan_nomor_hari (tanggal, nomor_antrian),
  KEY idx_bk_layanan_tanggal_status (tanggal,status),
  KEY idx_bk_layanan_siswa_tanggal (siswa_id,tanggal),
  KEY idx_bk_layanan_tapel (tahun_pelajaran_id),
  KEY idx_bk_layanan_petugas (petugas_id),
  CONSTRAINT fk_bk_layanan_siswa FOREIGN KEY (siswa_id) REFERENCES siswa(id) ON UPDATE CASCADE,
  CONSTRAINT fk_bk_layanan_tapel FOREIGN KEY (tahun_pelajaran_id) REFERENCES tahun_pelajaran(id) ON UPDATE CASCADE,
  CONSTRAINT fk_bk_layanan_kelas FOREIGN KEY (kelas_id) REFERENCES master_kelas(id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_bk_layanan_petugas FOREIGN KEY (petugas_id) REFERENCES guru(id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_bk_layanan_created FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
