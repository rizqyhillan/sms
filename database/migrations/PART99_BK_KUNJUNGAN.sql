CREATE TABLE IF NOT EXISTS bk_kunjungan (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  siswa_id BIGINT UNSIGNED NOT NULL,
  tahun_pelajaran_id BIGINT UNSIGNED NOT NULL,
  kelas_id BIGINT UNSIGNED NULL,
  tanggal DATE NOT NULL,
  waktu_kunjungan TIME NOT NULL,
  jenis_kunjungan ENUM('konseling','konsultasi','rujukan','administratif','lainnya') NOT NULL DEFAULT 'konseling',
  keterangan_singkat VARCHAR(255) NULL,
  metode ENUM('QR','USB','MANUAL') NOT NULL DEFAULT 'QR',
  petugas_id BIGINT UNSIGNED NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_bk_kunj_siswa (siswa_id),
  KEY idx_bk_kunj_tapel (tahun_pelajaran_id),
  KEY idx_bk_kunj_tanggal (tanggal),
  KEY idx_bk_kunj_petugas (petugas_id),
  CONSTRAINT fk_bk_kunj_siswa FOREIGN KEY (siswa_id) REFERENCES siswa(id) ON UPDATE CASCADE,
  CONSTRAINT fk_bk_kunj_tapel FOREIGN KEY (tahun_pelajaran_id) REFERENCES tahun_pelajaran(id) ON UPDATE CASCADE,
  CONSTRAINT fk_bk_kunj_kelas FOREIGN KEY (kelas_id) REFERENCES master_kelas(id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_bk_kunj_petugas FOREIGN KEY (petugas_id) REFERENCES guru(id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_bk_kunj_created FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
